const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = ts.transpileModule(fs.readFileSync('src/lib/cohort-selection.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const selection = {};
vm.runInNewContext(source, { exports: selection, URLSearchParams });
const { resolveCohort, cohortSwitchHref, cohortToday } = selection;
const cohort = (id, status, starts_on, ends_on, created_at = `${starts_on}T00:00:00Z`) => ({ id, status, starts_on, ends_on, created_at });
const old = cohort('old', 'active', '2025-01-01', '2025-12-31');
const current = cohort('current', 'active', '2026-10-01', '2026-12-31');
const future = cohort('future', 'active', '2027-01-01', '2027-12-31');
const archived = cohort('archived', 'archived', '2026-10-20', '2026-12-31');
const today = '2026-10-27';
const choose = (items, explicit) => resolveCohort(items, explicit, today)?.id ?? null;
assert.equal(choose([old, current, future, archived]), 'current');
assert.equal(choose([old, current, future, archived], 'old'), 'old');
assert.equal(choose([old, current, archived], 'archived'), 'archived');
assert.equal(choose([old, current], 'inaccessible'), 'current');
assert.equal(choose([old, future]), 'old');
assert.equal(choose([archived, future]), 'archived');
assert.equal(choose([future]), 'future');
assert.equal(choose([]), null);
assert.equal(choose([old, { ...current, starts_on: today, ends_on: today }]), 'current');
assert.equal(choose([current, cohort('later', 'active', '2026-10-15', null)]), 'later');
assert.equal(choose([current, { ...current, id: 'newer', created_at: '2026-10-05T00:00:00Z' }]), 'newer');
assert.equal(choose([{ ...current, id: 'z' }, { ...current, id: 'a' }]), 'a');
assert.equal(choose([{ ...current, id: 'a' }, { ...current, id: 'z' }]), 'a');
assert.equal(choose([cohort('undated', 'active', null, null), current]), 'current');
// Live metadata: Cohort 3 is already running but still marked planning.
const ct2 = cohort('ct2', 'active', '2026-06-27', '2026-08-08');
const ct3 = cohort('ct3', 'planning', '2026-10-24', '2026-11-28');
const planned = cohort('ct4', 'planning', '2027-01-01', '2027-02-28');
assert.equal(choose([ct2, ct3, planned]), 'ct3');
assert.equal(choose([planned, ct3, ct2]), 'ct3');
assert.equal(choose([ct2, ct3, planned], 'ct2'), 'ct2');
assert.equal(choose([ct2, planned]), 'ct2');
assert.equal(choose([ct2, { ...ct3, starts_on: null }]), 'ct2');
assert.equal(choose([ct2, { ...ct3, status: 'completed' }]), 'ct2');
assert.equal(choose([ct2, { ...ct3, status: 'archived' }]), 'ct2');
assert.equal(cohortToday(new Date('2026-10-26T22:59:59Z')), '2026-10-26');
assert.equal(cohortToday(new Date('2026-10-26T23:00:00Z')), '2026-10-27');
assert.equal(cohortToday(new Date('2026-10-27T23:30:00Z')), '2026-10-28');
const before = [old, current];
choose(before);
assert.deepEqual(before.map((item) => item.id), ['old', 'current']);
assert.equal(cohortSwitchHref('/participants', 'cohort=old&page=8&cursor=stale&status=Active', 'current'), '/participants?cohort=current&status=Active');
assert.equal(cohortSwitchHref('/tasks?view=mine', 'page=2', 'old'), '/tasks?view=mine&cohort=old');
console.log('Cohort selection: current active/planning, expired/future/archived, Lagos midnight, explicit accessible scope, inclusive dates, deterministic ties, immutable inputs and pagination reset passed.');
